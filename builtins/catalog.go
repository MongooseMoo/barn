// Descriptors assembles the native catalog with owner-supplied functions such
// as the VM's eval and pass. Missing VM functions leave the native-only layout
// unchanged. Additional functions follow the historical layout in input order.
func Descriptors(additional ...Descriptor) []Descriptor {
	families := [][]Descriptor{
		typesDescriptors(),
		stringsDescriptors(),
		mathDescriptors(),
		ansiDescriptors(),
		listsDescriptors(),
		mapsDescriptors(),
		objectsDescriptors(),
		objectsHierarchyDescriptors(),
		objectsMovementDescriptors(),
		objectsPlayersDescriptors(),
		objectsMiscDescriptors(),
		propertiesDescriptors(),
		verbsDescriptors(),
		jsonDescriptors(),
		networkDescriptors(),
		connectionDescriptors(),
		cryptoDescriptors(),
		argon2Descriptors(),
		curlDescriptors(),
		urlDescriptors(),
		pcreDescriptors(),
		fileioDescriptors(),
		sqliteDescriptors(),
		systemDescriptors(),
		signaturesDescriptors(),
		tasksDescriptors(),
		limitsDescriptors(),
		gcDescriptors(),
		unicodeDescriptors(),
		tzOffsetDescriptors(),
	}
	byName := make(map[string]Descriptor)
	add := func(d Descriptor) {
		if _, ok := byName[d.Name]; ok {
			panic(fmt.Sprintf("duplicate catalog builtin %q", d.Name))
		}
		byName[d.Name] = d
	}
	for _, family := range families {
		for _, d := range family {
			add(d)
		}
	}
	for _, d := range additional {
		add(d)
	}
	_, hasEval := byName["eval"]
	_, hasPass := byName["pass"]
	if hasEval != hasPass {
		panic("VM catalog must contribute both eval and pass")
	}
	result := make([]Descriptor, 0, len(byName))
	for _, name := range builtinLayout {
		d, ok := byName[name]
		if !ok {
			if name == "eval" || name == "pass" {
				continue
			}
			panic(fmt.Sprintf("missing catalog builtin %q", name))
		}
		result = append(result, d)
		delete(byName, name)
	}
	for _, d := range additional {
		if _, ok := byName[d.Name]; ok {
			result = append(result, d)
			delete(byName, d.Name)
		}
	}
	if len(byName) != 0 {
		panic("native builtin missing from bytecode layout")
	}
	return result
}
